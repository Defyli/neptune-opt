# Keep source files alive for Triton's lazy compiler and AOT packaging. TemporaryDirectory
# owns cleanup (including failed imports); atexit releases it at normal interpreter shutdown.
_GEN_OWNER = tempfile.TemporaryDirectory(prefix="neptune_codegen_")
_GEN_DIR = _GEN_OWNER.name
_GEN_RELEASED = False


def _release_generated_dir() -> None:
    global _GEN_RELEASED
    if not _GEN_RELEASED:
        _GEN_OWNER.cleanup()
        _GEN_RELEASED = True


atexit.register(_release_generated_dir)
_CACHE: dict[tuple, Callable | tuple[Callable, Callable]] = {}


# ---------------------------------------------------------------- codegen
_TEMPLATE = '''\
@triton.jit
def {name}(x_ptr, out_ptr, rows, ncols, stride_row, stride_col, BLOCK: tl.constexpr):
    row = tl.program_id(0)
    if row < rows:
        m = tl.full((), 0.0, tl.float32)
        acc = tl.full((), {acc_init}, tl.float32)
        seen = tl.full((), 0, tl.int32)
        status = tl.full((), 0, tl.int32)
        for off in range(0, ncols, BLOCK):
            mb, ab, vb, sb = {name}_chunk(x_ptr, row, off, ncols, stride_row, stride_col, BLOCK)
            m, acc, seen, status = {name}_merge_state(m, acc, seen, status, mb, ab, vb, sb)
        tl.store(out_ptr + row, {finalize})
'''


# The two-pass plan. A scalar repair does not suffice; extended carried state could
# enable a future single-pass plan. The term needs the FINAL producer value, so
# the row is read twice and the producer is held constant in the second pass. Kept as a
# separate template rather than a branch inside `_TEMPLATE` so the one-pass algebra stays
# unchanged. Both plans use explicit column strides; older manual launches need that argument.
_TEMPLATE_TWO_PASS = '''\
# AUTO-GENERATED by neptune_codegen -- do not edit.
# skeleton={name!r}
# doc={doc!r}
#
# TWO-PASS plan: this operator has no repair, because its term reads the FINAL producer
# value (a mean, say) rather than a running one. Pass 1 reduces the producer; pass 2 reduces
# the consumer with the producer held constant, so the repair is the identity by
# construction. One kernel, two reads of the row, no materialised intermediate.
import triton
import triton.language as tl


@triton.jit
def {name}(x_ptr, out_ptr, rows, ncols, stride_row, stride_col,
           BLOCK: tl.constexpr):
    row = tl.program_id(0)
    if row < rows:
        base = x_ptr + row * stride_row
        # ---- pass 1: the producer reduction
        m = {prod_init}
        for off in range(0, ncols, BLOCK):
            idx = off + tl.arange(0, BLOCK)
            mask = idx < ncols
            v = tl.load(base + idx * stride_col, mask=mask, other=0.0).to(tl.float32)
            {abs_line}# Out-of-range lanes load as 0.0 and must not enter the producer
            # update; the fill is the reducer's identity, so masked lanes always lose.
            {prod_update}
            m = m_new
        # ---- the producer is FINAL here: pass 1 reduced `producer_expr`, whose scale (the
        # 1/N of a mean, declared as `c / N`) is already in the operand. This is the value the
        # term reads, and it does not move again.
        # ---- pass 2: the consumer reduction, with the producer constant
        acc = {acc_init}
        for off in range(0, ncols, BLOCK):
            idx = off + tl.arange(0, BLOCK)
            mask = idx < ncols
            v = tl.load(base + idx * stride_col, mask=mask, other=0.0).to(tl.float32)
            den = {den_src}
            {acc_update}
        tl.store(out_ptr + row, {finalize})
'''


MAX_SPLIT_PARTS = 4096


def validate_plan(plan: str) -> None:
    if plan not in ("serial", "split"):
        raise ValueError(f"unknown reduction plan {plan!r}; expected 'serial' or 'split'")


def split_launch_shape(ncols, block: int) -> tuple[int, int]:
    """Explicit split refuses unknown width/capacity rather than concretising SymInts."""
    if type(ncols) is not int:
        raise NotImplementedError("explicit split requires a concrete width; use plan='serial' for dynamic width")
    if type(block) is not int or block <= 0 or block & (block - 1):
        raise ValueError("split BLOCK must be a positive power of two")
    if ncols <= 0:
        raise ValueError("split requires positive width")
    nparts = (ncols + block - 1) // block
    if nparts > MAX_SPLIT_PARTS:
        raise NotImplementedError(f"split needs {nparts} partials, exceeding capacity {MAX_SPLIT_PARTS}; use serial")
    return nparts, 1 << (nparts - 1).bit_length()


def _emit_state_plan(sk: Skeleton, values: dict | None, plan: str) -> str:
    helpers = emit_state_helpers(sk, values)
    header = ('# AUTO-GENERATED: exact real-algebra repair, not bitwise IEEE associativity.\n'
              f'# skeleton={sk.name!r}, plan={plan!r}; non-log requires finite reachable arithmetic.\n'
              'import triton\nimport triton.language as tl\n\n')
    finalize = state_finalize_source(sk, values)
    if plan == "serial":
        return header + helpers + _TEMPLATE.format(
            name=sk.name, acc_init=consumer_init(sk), finalize=finalize)
    return header + helpers + f'''@triton.jit
def {sk.name}_partial(x_ptr, partial_m, partial_a, partial_v, partial_status,
                       rows, ncols, stride_row, stride_col, nparts, BLOCK: tl.constexpr):
    row = tl.program_id(0)
    part = tl.program_id(1)
    if row < rows:
        m, acc, seen, status = {sk.name}_chunk(x_ptr, row, part * BLOCK, ncols, stride_row, stride_col, BLOCK)
        slot = row * nparts + part
        tl.store(partial_m + slot, m)
        tl.store(partial_a + slot, acc)
        tl.store(partial_v + slot, seen)
        tl.store(partial_status + slot, status)


@triton.jit
def {sk.name}_merge(partial_m, partial_a, partial_v, partial_status, out_ptr,
                     rows, ncols, nparts, MERGE_BLOCK: tl.constexpr):
    row = tl.program_id(0)
    if row < rows:
        part = tl.arange(0, MERGE_BLOCK)
        slot = row * nparts + part
        mask = part < nparts
        m = tl.load(partial_m + slot, mask=mask, other=0.0)
        acc = tl.load(partial_a + slot, mask=mask, other={consumer_init(sk)})
        seen = tl.load(partial_v + slot, mask=mask, other=0)
        status = tl.load(partial_status + slot, mask=mask, other=0)
        m, acc, seen, status = tl.reduce((m, acc, seen, status), 0, {sk.name}_merge_state)
        tl.store(out_ptr + row, {finalize})
'''


def emit_kernel_source(sk: Skeleton, values: dict | None = None, *, plan: str = "serial") -> str:
    """Render a serial fold or explicitly requested split/merge; never autotune plans."""
    validate_plan(plan)
    check_supported(sk)
    if plan == "split" and sk.two_pass:
        raise NotImplementedError("two_pass needs extended carried state; split refused")
    if sk.two_pass:
        return _TEMPLATE_TWO_PASS.format(
            name=sk.name,
            doc=sk.doc,
            prod_init=producer_init(sk),
            acc_init=consumer_init(sk),
            prod_update=producer_update(sk, values),
            acc_update=consumer_fold_no_repair(sk, values),
            abs_line="a = tl.abs(v)\n            " if producer_operand(sk, values) == "a" else "",
            den_src=denominator_expr(sk),
            finalize=finalize_source(sk, values),
        )
    return _emit_state_plan(sk, values, plan)


def generated_path(name: str, values: dict | None = None, *, plan: str = "serial") -> str:
    """One file per (skeleton, parameter values): the values are baked into the source."""
    if _GEN_RELEASED:
        raise RuntimeError("generated source directory has been released")
    validate_plan(plan)
    suffix = "" if plan == "serial" else "_plan_split"
    return os.path.join(_GEN_DIR, f"neptune_gen_{name}{parameter_tag(values)}{suffix}.py")


def compile_skeleton(name: str, values: dict | None = None, force: bool = False, *, plan: str = "serial"):
    """Generate -> write to a real file -> import -> return the kernel object."""
    if _GEN_RELEASED:
        raise RuntimeError("generated source directory has been released")
    validate_plan(plan)
    cache_key = (name, parameter_identity(values), plan)
    if not force and cache_key in _CACHE:
        return _CACHE[cache_key]
    if name not in SKELETONS:
        raise KeyError(f"unknown skeleton {name!r}; have {all_registered()}")
    sk = SKELETONS[name]
    src = emit_kernel_source(sk, values, plan=plan)
    mod_name = f"neptune_gen_{name}{parameter_tag(values)}_plan_{plan}"
    path = generated_path(name, values, plan=plan)
    with open(path, "w") as f:
        f.write(src)
    spec = importlib.util.spec_from_file_location(mod_name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[mod_name] = mod
    try:
        spec.loader.exec_module(mod)
        kernel = (getattr(mod, name) if plan == "serial" else
                  (getattr(mod, name + "_partial"), getattr(mod, name + "_merge")))
    except BaseException:
        sys.modules.pop(mod_name, None)
        raise
    _CACHE[cache_key] = kernel
    return kernel


_STATE_CACHE: dict[tuple, Callable | tuple] = {}


def compile_state_reduction(name: str, params=None, *, plan="serial"):
    """Compile a certified structured backend under the existing source owner."""
    from neptune_codegen.skeleton import state_reduction_spec
    from neptune_codegen.algebra import derive_state_certificate
    from neptune_codegen.emitters import emit_rms_state_source

    if _GEN_RELEASED:
        raise RuntimeError("generated source directory has been released")
    validate_plan(plan)
    if name != "rms_norm":
        raise NotImplementedError("this structured compiler implements RMSNorm; segments use the serial backend")
    params = dict(params or {})
    spec = state_reduction_spec(name)
    derive_state_certificate(spec)
    # Validate even a cache hit, including misspelled parameters.
    source = emit_rms_state_source(spec, params, plan=plan)
    key = (spec, parameter_identity(params), plan)
    if key in _STATE_CACHE:
        return _STATE_CACHE[key]
    module_name = f"neptune_state_{name}{parameter_tag(params)}_plan_{plan}"
    path = os.path.join(_GEN_DIR, module_name + ".py")
    with open(path, "w") as file:
        file.write(source)
    module_spec = importlib.util.spec_from_file_location(module_name, path)
    module = importlib.util.module_from_spec(module_spec)
    sys.modules[module_name] = module
    try:
        module_spec.loader.exec_module(module)
        kernel = module.rms_norm if plan == "serial" else (module.rms_norm_partial, module.rms_norm_map)
    except BaseException:
        sys.modules.pop(module_name, None)
        raise
    _STATE_CACHE[key] = kernel
    return kernel


def validate_rms_inputs(x, gamma, params=None, *, plan="serial", metadata=False):
    """Full-vector RMSNorm ABI; symbolic batch survives unchanged."""
    import math
    import torch

    validate_plan(plan)
    _validate_row_last(x, metadata=metadata)
    params = dict(params or {})
    eps = params.get("eps")
    if params.keys() != {"eps"} or type(eps) not in (int, float) or not math.isfinite(eps) or eps <= 0:
        raise ValueError("RMSNorm requires an explicit finite positive eps")
    if gamma.layout != torch.strided or gamma.ndim != 1:
        raise ValueError("RMSNorm gamma must be a strided 1D tensor")
    if gamma.dtype != x.dtype or gamma.device != x.device:
        raise ValueError("RMSNorm gamma dtype/device must match input")
    torch._check(gamma.shape[0] == x.shape[-1], lambda: "RMSNorm gamma width must match input")
    # Resident input storage has a real resource bound. Never specialize a hinted
    # dynamic width: an explicit split/another backend is required instead.
    if type(x.shape[-1]) is not int:
        raise NotImplementedError("RMSNorm first backend requires a static feature width")
    if plan == "serial" and x.shape[-1] > 32768:
        raise NotImplementedError("resident RMSNorm width exceeds 32768; request split explicitly")
    if plan == "split":
        split_launch_shape(x.shape[-1], 1024)
    return x.shape


def launch_rms_norm(kernel, x, gamma, out, *, plan="serial", wrapper=None):
    """Shared direct/AOTI launch path; required copies and scratch are included."""
    import torch

    if wrapper is None:
        def wrapper(function):
            return function
    flat, rows, width = _row_last_layout(x)
    if isinstance(rows, int) and rows == 0:
        return
    if plan == "serial":
        block = 1 << (width - 1).bit_length()
        warps = 4 if block <= 4096 else 8
        wrapper(kernel)[(rows,)](flat, gamma, out, rows, width, flat.stride(0), flat.stride(1),
                                gamma.stride(0), BLOCK=block, num_warps=warps, enable_fp_fusion=False)
        return
    parts, merge_block = split_launch_shape(width, 1024)
    totals = torch.empty((rows, parts), device=x.device, dtype=torch.float32)
    counts = torch.empty((rows, parts), device=x.device, dtype=torch.int64)
    partial, output_map = kernel
    wrapper(partial)[(rows, parts)](flat, totals, counts, rows, width, flat.stride(0), flat.stride(1),
                                    parts, BLOCK=1024, num_warps=4, enable_fp_fusion=False)
    wrapper(output_map)[(rows, parts)](flat, gamma, totals, counts, out, rows, width,
                                     flat.stride(0), flat.stride(1), gamma.stride(0), parts,
                                     BLOCK=1024, MERGE_BLOCK=merge_block, num_warps=4,
                                     enable_fp_fusion=False)


def run_rms_norm(x, gamma, *, eps: float = 1e-6, plan="serial"):
    """Direct structured execution; CPU analysis remains available through Fake/meta."""
    import torch
    from torch._subclasses.fake_tensor import FakeTensor

    params = {"eps": eps}
    metadata = isinstance(x, FakeTensor) or x.device.type == "meta"
    shape = validate_rms_inputs(x, gamma, params, plan=plan, metadata=metadata)
    out = torch.empty(shape, device=x.device, dtype=x.dtype)
    if metadata or x.numel() == 0:
        return out
    kernel = compile_state_reduction("rms_norm", params, plan=plan)
    launch_rms_norm(kernel, x, gamma, out, plan=plan)
    return out


def _validate_row_last(x, *, metadata: bool = False):
    """Check the supported runtime contract without concretising dynamic dimensions."""
    import torch

    if x.layout != torch.strided:
        raise TypeError("Neptune requires a strided tensor")
    if x.ndim < 1:
        raise ValueError("Neptune row-last reductions require rank >= 1")
    if x.dtype not in (torch.float16, torch.bfloat16, torch.float32):
        raise TypeError(f"unsupported Neptune dtype {x.dtype}; expected float16/bfloat16/float32")
    if not metadata and x.device.type != "cuda":
        raise ValueError(f"unsupported Neptune device {x.device}; execution requires CUDA")
    # max producers and several finalizers are undefined on empty rows. Reject width zero
    # uniformly rather than silently inventing per-skeleton empty-reduction identities.
    torch._check(x.shape[-1] > 0, lambda: "Neptune requires positive last-dimension width")


def _row_last_layout(x):
    """Flatten ONLY leading dimensions; reshape copies exactly when a view is impossible.

    Keep two-dimensional strides unchanged, including sliced/transposed/expanded columns.
    Products remain SymInts; neither row count nor stride is converted with int().
    """
    rows = 1
    for size in x.shape[:-1]:
        rows = rows * size
    ncols = x.shape[-1]
    return x.reshape(rows, ncols), rows, ncols


def launch_reduction(kernel, plan, x2, out, rows, ncols, block, num_warps, *, wrapper=None):
    """Shared direct/custom-op launch ABI; allocation is traceable torch code."""
    import torch

    validate_plan(plan)
    if wrapper is None:
        def wrapper(fn):
            return fn
    if plan == "serial":
        wrapper(kernel)[(rows,)](x2, out, rows, ncols, x2.stride(0), x2.stride(1),
                                BLOCK=block, num_warps=num_warps)
        return
    nparts, merge_block = split_launch_shape(ncols, block)
    partial_m = torch.empty((rows, nparts), device=x2.device, dtype=torch.float32)
    partial_a = torch.empty((rows, nparts), device=x2.device, dtype=torch.float32)
    partial_v = torch.empty((rows, nparts), device=x2.device, dtype=torch.int32)
    partial_status = torch.empty((rows, nparts), device=x2.device, dtype=torch.int32)
    partial, merge = kernel
    wrapper(partial)[(rows, nparts)](x2, partial_m, partial_a, partial_v, partial_status,
                                    rows, ncols, x2.stride(0), x2.stride(1), nparts,
                                    BLOCK=block, num_warps=num_warps)
    wrapper(merge)[(rows,)](partial_m, partial_a, partial_v, partial_status, out,
                          rows, ncols, nparts, MERGE_BLOCK=merge_block, num_warps=num_warps)


def run(name: str, x, block: int | None = None, num_warps: int | None = None,
        keepdim: bool = False, plan: str = "serial", **params):
    """Execute the generated kernel, reducing over the last dimension.

    `params` supplies the extra scalars the skeleton declared, by kernel argument name
    (e.g. `run("lse_alibi", x, alpha=0.5)`). Rank >= 1 returns x.shape[:-1]; keepdim
    appends a singleton dimension. Column strides are inferred, never required from callers.
    Real execution supports CUDA float16/bfloat16/float32; Fake/meta returns metadata only.

    `block` and `num_warps` default to the measured configuration for the shape (see
    `neptune_codegen.autotune`), which is also what the shipped op uses -- this function exists so
    tests and experiments can launch the kernel directly, and it must not quietly differ from the
    op that ships.
    """
    import torch

    from neptune_codegen.autotune import best_config
    from neptune_codegen.skeleton import param_defaults

    # Fill the skeleton's declared defaults for anything the caller did not give, the same way
    # `neptune_opt.<op>()` does. Without this, `run("logsumexp", x)` raised
    # `KeyError: no value supplied for scalar parameter` -- a footgun that silently turned a whole
    # measurement run into `inf` timings (experiments/gpu_m22_autotune.py, first attempt).
    from torch._subclasses.fake_tensor import FakeTensor

    metadata = isinstance(x, FakeTensor) or x.device.type == "meta"
    _validate_row_last(x, metadata=metadata)
    params = {**param_defaults(name), **(params or {})}
    validate_plan(plan)
    if plan == "split":
        block = 1024 if block is None else block
        num_warps = 4 if num_warps is None else num_warps
        from neptune_codegen.algebra import derive_merge_certificate
        derive_merge_certificate(SKELETONS[name], params)
        split_launch_shape(x.shape[-1], block if block is not None else 1024)
    shape = x.shape[:-1] + ((1,) if keepdim else ())
    out = torch.empty(shape, device=x.device, dtype=x.dtype)
    if metadata:
        return out
    x2, rows, ncols = _row_last_layout(x)
    if isinstance(rows, int) and rows == 0:
        return out
    kernel = (compile_skeleton(name, params) if plan == "serial" else
              compile_skeleton(name, params, plan=plan))
    if block is None or num_warps is None:
        cfg = best_config(rows, ncols, x.dtype, x.device)
        block = cfg[0] if block is None else block
        num_warps = cfg[1] if num_warps is None else num_warps
    launch_reduction(kernel, plan, x2, out, rows, ncols, block, num_warps)
    return out
