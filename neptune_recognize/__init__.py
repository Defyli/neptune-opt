"""
Recognition derived from the algebra.

Why this file exists
--------------------
The generator turns a skeleton into a kernel; the other half of the job is deciding WHICH
skeleton a graph implements. That decision was a hand-written if/elif table -- which is the
same "preset skeleton plus hand-written snippet" shape the generator itself was criticised
for. The table does not scale and it silently disagrees with the registry next to it.

Here recognition is derived in two steps:

  1. INTERPRET the ATen graph symbolically over one data symbol `c`: every pointwise op
     becomes a sympy expression, and each reduction installs a fresh symbol standing for
     its result. This yields the pair the algebra actually talks about:
         phi(c)          what the max-like reduction reduces over
         psi(c, s)       what the sum-like reduction reduces over
  2. MATCH that pair against every REGISTERED skeleton, comparing the skeleton's own
     producer expression and term expression.

Consequences worth stating plainly:

  * a new operator extends recognition by being registered -- no pattern row is written
  * recognition cannot disagree with the generator, because it reads the same registry
  * scalar parameters (alpha, N, beta) are INFERRED from the graph when the caller does
    not supply them, which is how an ALiBi bias becomes a matched skeleton rather than an
    unmatched special case

The residual limitation is honest and unchanged: this recognises graphs that were
generated by DECOMPOSING the operator in the natural way. Any recogniser must decide what
it accepts, and a symbolic interpreter over the ATen op set is a much larger acceptance
surface than a per-operator row, but it is still not "any equivalent computation".
"""
