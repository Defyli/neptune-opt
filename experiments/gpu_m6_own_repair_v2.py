"""
Milestone 6 — install our own repair arithmetic into the STREAMING online-softmax path
and prove numerical control.

Background
----------
* milestone 3: register-resident path intercepted; a rewrite DID change numerics.
* milestone 4: both paths intercepted (markers reached the compiled kernel).
* milestone 5: installing a replacement compiled into the graph, but the target kernel
  failed. Two distinct causes were found, both instructive:
    (a) TypeError: the emitted call site passes FEWER arguments than the published
        signature -> the replacement must make `strict_signed_zero` optional.
    (b) NameError: "Cannot access global variable REPAIR_SCALE from within @jit'ed
        function ... Triton kernels can only access global variables that are
        instantiated as constexpr."
        -> a mutable module-level knob is NOT usable inside a jitted function.

Fix: build two CONCRETE jitted functions with the factor baked in as a source literal.
A literal is a genuine compile-time constant, so Triton accepts it.

Run: python3 gpu_m6_own_repair.py
"""
from __future__ import annotations

import importlib.util
import os
import shutil
import sys
import tempfile

import torch

assert torch.cuda.is_available()
os.environ["TORCHINDUCTOR_FX_GRAPH_CACHE"] = "0"

import triton  # noqa: E402
import triton.language as tl  # noqa: E402
import torch._inductor.runtime.triton_helpers as TH  # noqa: E402
from torch._inductor.runtime.triton_helpers import exp, maximum  # noqa: E402

SHAPE = (64, 4096)          # the shape where the streaming combine is really used
_orig_combine = TH.online_softmax_combine

_TEMPLATE = '''
@triton.jit
def _neptune_combine(lhs_max, lhs_sum, rhs_max,
                     use_fast_math: tl.constexpr = False,
                     strict_signed_zero: tl.constexpr = False):
    out_max = maximum(lhs_max, rhs_max)
    lhs_scale = tl.where(
        out_max == float("-inf"), 1.0, exp(lhs_max - out_max, use_fast_math)
    ) * {factor}
    rhs_scale = tl.where(
        out_max == float("-inf"), 1.0, exp(rhs_max - out_max, use_fast_math)
    )
    return out_max, lhs_sum * lhs_scale + rhs_scale
'''


_HELPER_DIR = tempfile.mkdtemp(prefix="neptune_helpers_")
_TRITON_HOME = tempfile.mkdtemp(prefix="neptune_triton_")
os.environ["TRITON_HOME"] = _TRITON_HOME


def make_combine(factor: str):
    """Compile a repair helper with `factor` baked in as a literal.

    The helper MUST live in a real file: Triton reads the function source with
    `inspect.getsourcelines` at decoration time, so an `exec`-generated function fails
    with `OSError: could not get source code`. Generating a module file is also what a
    real code-generating module would do.
    """
    name = f"neptune_repair_{factor.replace('.', '_')}"
    path = os.path.join(_HELPER_DIR, f"{name}.py")
    header = (
        "# AUTO-GENERATED by the Neptune-style repair module.\n"
        "import triton\n"
        "import triton.language as tl\n"
        "from torch._inductor.runtime.triton_helpers import exp, maximum\n"
    )
    body = _TEMPLATE.format(factor=factor).replace(
        "def _neptune_combine(", "def online_softmax_combine("
    )
    with open(path, "w") as f:
        f.write(header + body)
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod.online_softmax_combine


COMBINE_FAITHFUL = make_combine("1.0")     # must reproduce the reference
COMBINE_PERTURBED = make_combine("1.5")    # must move the result

print("=" * 96)
print("MILESTONE 6 — own repair arithmetic in the streaming online-softmax path")
print(f"torch {torch.__version__}  triton {triton.__version__}  shape {SHAPE}")
print("=" * 96)


def probe(t):
    m = t.amax(dim=-1, keepdim=True)
    e = (t - m).exp()
    return e / e.sum(dim=-1, keepdim=True)


torch.manual_seed(0)
x = torch.randn(*SHAPE, device="cuda")
ref = probe(x)


def run(label):
    """Compile and run.

    NOTE: the per-run isolation is not cosmetic. Triton caches compiled kernels keyed by
    source, but the *emitted* kernel source is byte-identical between our two helpers
    (they differ only inside a referenced helper module), so without isolating
    TRITON_HOME the second compile silently reuses the first binary and the perturbation
    appears to do nothing. That exact false negative cost several iterations here.
    """
    torch._dynamo.reset()
    cache = tempfile.mkdtemp(prefix=f"m6_{label}_")
    os.environ["TORCHINDUCTOR_CACHE_DIR"] = cache
    with torch.no_grad():
        out = torch.compile(probe, dynamic=False)(x)
    used = False
    for dp, _d, fs in os.walk(cache):
        for f in fs:
            if f.endswith(".py"):
                t = open(os.path.join(dp, f), encoding="utf-8", errors="replace").read()
                if "online_softmax_combine" in t:
                    used = True
    shutil.rmtree(cache, ignore_errors=True)
    return (out - ref).abs().max().item(), used


def attempt(impl, label):
    TH.online_softmax_combine = impl
    try:
        err, used = run(label)
        return err, used, None
    except Exception as e:  # noqa: BLE001
        return float("nan"), False, f"{type(e).__name__}: {str(e)[:300]}"


print("\n[1] control — faithful replacement (factor = 1.0)")
err_ok, used_ok, fail_ok = attempt(COMBINE_FAITHFUL, "ok")
if fail_ok:
    print(f"    FAILED: {fail_ok}")
else:
    print(f"    combine referenced in kernel : {used_ok}")
    print(f"    max|compiled - reference|    = {err_ok:.3e}")

print("\n[2] perturbed — our repair arithmetic (factor = 1.5)")
err_bad, used_bad, fail_bad = attempt(COMBINE_PERTURBED, "bad")
if fail_bad:
    print(f"    FAILED: {fail_bad}")
else:
    print(f"    combine referenced in kernel : {used_bad}")
    print(f"    max|compiled - reference|    = {err_bad:.3e}")

print("\n" + "=" * 96)
control_ok = fail_ok is None and err_ok < 1e-6
moved = fail_bad is None and err_bad > 1e-4
print("EVIDENCE")
print(f"    replacement compiled and used : {fail_ok is None and fail_bad is None}")
print(f"    triton cache isolated per run : {os.environ['TRITON_HOME']}")
print(f"    control numerics correct      : {control_ok}  (err {err_ok:.3e})")
print(f"    perturbation moved the result : {moved}  (err {err_bad:.3e})")
print()
if control_ok and moved:
    print("""VERDICT: a module can SUPPLY the repair arithmetic of Inductor's streaming
reduction, from outside the torch installation.

  The emitted kernel contains only the CALL `triton_helpers.online_softmax_combine(...)`;
  replacing that attribute changes what the compiled kernel computes. A faithful copy
  reproduces the reference; scaling the rescale factor inside the replacement moves the
  result. The body of the repair term is therefore substitutable.

  A general (f, g, h) module can now:
    1. derive h symbolically                      [repairlib]
    2. classify whether h may be folded           [repairlib]
    3. emit h-specific Triton arithmetic          [milestones 3, 6]
    4. make the graph select it per operator      [REMAINING - ordinary plumbing]""")
else:
    print("""NOT YET — see the failures above. Both known Triton traps are already fixed
  here (optional-arg signature, literal instead of global), so a remaining failure
  points at how the kernel resolves the helper name rather than at our arithmetic.""")
print("=" * 96)

TH.online_softmax_combine = _orig_combine
