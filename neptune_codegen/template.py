"""
Rendering the kernel and compiling it into a real Triton function.
"""
from __future__ import annotations

import dataclasses
import importlib.util
import os
import random
import sys
import tempfile

import sympy as sp

from neptune_codegen.emitters import (bias_line, check_supported, consumer_fold_no_repair,
    consumer_init, consumer_update, denominator_expr, guard_value,
    producer_init, producer_operand, producer_update, scale_source, term_source,
    finalize_source)
from neptune_codegen.skeleton import SKELETONS
from neptune_codegen.symbols import *  # noqa: F401,F403


_GEN_DIR = tempfile.mkdtemp(prefix="neptune_codegen_")


_CACHE: dict[str, Callable] = {}


# ---------------------------------------------------------------- codegen
_TEMPLATE = '''\
# AUTO-GENERATED by neptune_codegen -- do not edit.
# skeleton={name!r}
# doc={doc!r}
#
# Repair h(t, s, s') = t * R(s, s') is applied on every producer update, so the consumer
# reduction never needs a second traversal of the input.
import triton
import triton.language as tl


@triton.jit
def {name}(x_ptr, out_ptr, rows, ncols, stride_row,
           BLOCK: tl.constexpr):
    row = tl.program_id(0)
    if row < rows:
        base = x_ptr + row * stride_row
        m = {prod_init}
        acc = {acc_init}
        for off in range(0, ncols, BLOCK):
            idx = off + tl.arange(0, BLOCK)
            mask = idx < ncols
            v = tl.load(base + idx, mask=mask, other=0.0).to(tl.float32)
            {abs_line}# Out-of-range lanes load as 0.0 and must not enter the producer
            # update; the fill is the reducer's identity, so masked lanes always lose.
            {prod_update}
            # h(t, s, s') = a*t + b: `m` is the PREVIOUS producer value, so on the
            # first block the repair is the identity (nothing to rescale yet).
            # `den` is the fresh producer value as the repair and the term should see it:
            # floored wherever the generated source divides by it (an all-zero row would
            # otherwise compute 0/0 = nan), and raw wherever it does not -- a shift must
            # not be offset by the floor, and an exponent must not be rescaled by it.
            den = {den_src}
            scale = tl.where(m == {guard}, 1.0, {scale_src}){bias_line}
            {acc_update}
            m = m_new
        tl.store(out_ptr + row, {finalize})
'''


# The two-pass plan. Used when NO repair exists, which is precisely when a single pass is
# impossible: the term needs the FINAL producer value (g = (c - mean)^2 needs the mean), so
# the row is read twice and the producer is held constant in the second pass. Kept as a
# separate template rather than a branch inside `_TEMPLATE` so that the one-pass source stays
# byte-identical to what all the existing GPU evidence was produced with.
_TEMPLATE_TWO_PASS = '''\
# AUTO-GENERATED by neptune_codegen -- do not edit.
# skeleton={name!r}
# doc={doc!r}
#
# TWO-PASS plan: this operator has no repair, because its term reads the FINAL producer
# value (a mean, say) rather than a running one. Pass 1 reduces the producer; pass 2 reduces
# the consumer with the producer held constant, so the repair is the identity by
# construction. One kernel, two reads of the row, no materialised intermediate.
import triton
import triton.language as tl


@triton.jit
def {name}(x_ptr, out_ptr, rows, ncols, stride_row,
           BLOCK: tl.constexpr):
    row = tl.program_id(0)
    if row < rows:
        base = x_ptr + row * stride_row
        # ---- pass 1: the producer reduction
        m = {prod_init}
        for off in range(0, ncols, BLOCK):
            idx = off + tl.arange(0, BLOCK)
            mask = idx < ncols
            v = tl.load(base + idx, mask=mask, other=0.0).to(tl.float32)
            {abs_line}# Out-of-range lanes load as 0.0 and must not enter the producer
            # update; the fill is the reducer's identity, so masked lanes always lose.
            {prod_update}
            m = m_new
        # ---- the producer is FINAL here: pass 1 reduced `producer_expr`, whose scale (the
        # 1/N of a mean, declared as `c / N`) is already in the operand. This is the value the
        # term reads, and it does not move again.
        # ---- pass 2: the consumer reduction, with the producer constant
        acc = {acc_init}
        for off in range(0, ncols, BLOCK):
            idx = off + tl.arange(0, BLOCK)
            mask = idx < ncols
            v = tl.load(base + idx, mask=mask, other=0.0).to(tl.float32)
            den = {den_src}
            {acc_update}
        tl.store(out_ptr + row, {finalize})
'''


def emit_kernel_source(sk: Skeleton, values: dict | None = None) -> str:
    """Render Triton source for one skeleton, under its declared plan."""
    check_supported(sk)
    if sk.two_pass:
        return _TEMPLATE_TWO_PASS.format(
            name=sk.name,
            doc=sk.doc,
            prod_init=producer_init(sk),
            acc_init=consumer_init(sk),
            prod_update=producer_update(sk, values),
            acc_update=consumer_fold_no_repair(sk, values),
            abs_line="a = tl.abs(v)\n            " if producer_operand(sk, values) == "a" else "",
            den_src=denominator_expr(sk),
            finalize=finalize_source(sk, values),
        )
    return _TEMPLATE.format(
        name=sk.name,
        doc=sk.doc,
        prod_init=producer_init(sk),
        acc_init=consumer_init(sk),
        prod_update=producer_update(sk, values),
        acc_update=consumer_update(sk, values),
        abs_line="a = tl.abs(v)\n            " if producer_operand(sk, values) == "a" else "",
        init=sk.init,
        operand=producer_operand(sk, values),
        den_src=denominator_expr(sk),
        guard=guard_value(sk),
        scale_src=scale_source(sk, values),
        bias_line=bias_line(sk, values),
        term_src=term_source(sk, values),
        finalize=finalize_source(sk, values),
    )


def generated_path(name: str, values: dict | None = None) -> str:
    """One file per (skeleton, parameter values): the values are baked into the source."""
    tag = ""
    if values:
        tag = "_" + "_".join(f"{k}{float(v):g}" for k, v in sorted(values.items()))
    return os.path.join(_GEN_DIR, f"neptune_gen_{name}{tag}.py")


def compile_skeleton(name: str, values: dict | None = None, force: bool = False):
    """Generate -> write to a real file -> import -> return the kernel object."""
    cache_key = name + "|" + ",".join(f"{k}={float(v):g}" for k, v in sorted((values or {}).items()))
    if not force and cache_key in _CACHE:
        return _CACHE[cache_key]
    if name not in SKELETONS:
        raise KeyError(f"unknown skeleton {name!r}; have {all_registered()}")
    sk = SKELETONS[name]
    src = emit_kernel_source(sk, values)
    mod_name = f"neptune_gen_{name}_" + "".join(
        ch if ch.isalnum() else "_" for ch in cache_key.split("|", 1)[1])
    path = generated_path(name, values)
    with open(path, "w") as f:
        f.write(src)
    spec = importlib.util.spec_from_file_location(mod_name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[mod_name] = mod
    spec.loader.exec_module(mod)
    kernel = getattr(mod, name)
    _CACHE[cache_key] = kernel
    return kernel


def run(name: str, x, block: int | None = None, num_warps: int | None = None, **params):
    """Execute the generated kernel, reducing over the last dimension.

    `params` supplies the extra scalars the skeleton declared, by kernel argument name
    (e.g. `run("lse_alibi", x, alpha=0.5)`).

    `block` and `num_warps` default to the measured configuration for the shape (see
    `neptune_codegen.autotune`), which is also what the shipped op uses -- this function exists so
    tests and experiments can launch the kernel directly, and it must not quietly differ from the
    op that ships.
    """
    import torch

    from neptune_codegen.autotune import best_config
    from neptune_codegen.skeleton import param_defaults

    # Fill the skeleton's declared defaults for anything the caller did not give, the same way
    # `neptune_opt.<op>()` does. Without this, `run("logsumexp", x)` raised
    # `KeyError: no value supplied for scalar parameter` -- a footgun that silently turned a whole
    # measurement run into `inf` timings (experiments/gpu_m22_autotune.py, first attempt).
    params = {**param_defaults(name), **(params or {})}
    kernel = compile_skeleton(name, params)
    rows = x.shape[0]
    ncols = x.numel() // rows
    if block is None or num_warps is None:
        cfg = best_config(rows, ncols, x.dtype, x.device)
        block = cfg[0] if block is None else block
        num_warps = cfg[1] if num_warps is None else num_warps
    x2 = x.reshape(rows, ncols).contiguous()
    # The input's dtype, matching `as_triton_op` -- `run` exists so tests and experiments can
    # launch the kernel directly, and it must not quietly differ from the op that ships.
    out = torch.empty(rows, device=x.device, dtype=x.dtype)
    kernel[(rows,)](x2, out, rows, ncols, x2.stride(0), BLOCK=block, num_warps=num_warps)
    return out
