"""
Rendering the kernel and compiling it into a real Triton function.
"""
from __future__ import annotations

import dataclasses
import importlib.util
import os
import random
import sys
import tempfile

import sympy as sp

from neptune_codegen.emitters import (bias_line, check_supported, consumer_init,
    consumer_update, denominator_expr, guard_value, producer_init, producer_operand,
    producer_update, scale_source, term_source, finalize_source)
from neptune_codegen.skeleton import SKELETONS
from neptune_codegen.symbols import *  # noqa: F401,F403


_GEN_DIR = tempfile.mkdtemp(prefix="neptune_codegen_")


_CACHE: dict[str, Callable] = {}


# ---------------------------------------------------------------- codegen
_TEMPLATE = '''\
# AUTO-GENERATED by neptune_codegen -- do not edit.
# skeleton={name!r}
# doc={doc!r}
#
# Repair h(t, s, s') = t * R(s, s') is applied on every producer update, so the consumer
# reduction never needs a second traversal of the input.
import triton
import triton.language as tl


@triton.jit
def {name}(x_ptr, out_ptr, rows, ncols, stride_row,
           BLOCK: tl.constexpr):
    row = tl.program_id(0)
    if row < rows:
        base = x_ptr + row * stride_row
        m = {prod_init}
        acc = {acc_init}
        for off in range(0, ncols, BLOCK):
            idx = off + tl.arange(0, BLOCK)
            mask = idx < ncols
            v = tl.load(base + idx, mask=mask, other=0.0).to(tl.float32)
            {abs_line}# Out-of-range lanes load as 0.0 and must not enter the producer
            # update; the fill is the reducer's identity, so masked lanes always lose.
            {prod_update}
            # h(t, s, s') = a*t + b: `m` is the PREVIOUS producer value, so on the
            # first block the repair is the identity (nothing to rescale yet).
            # `den` is the fresh producer value as the repair and the term should see it:
            # floored wherever the generated source divides by it (an all-zero row would
            # otherwise compute 0/0 = nan), and raw wherever it does not -- a shift must
            # not be offset by the floor, and an exponent must not be rescaled by it.
            den = {den_src}
            scale = tl.where(m == {guard}, 1.0, {scale_src}){bias_line}
            {acc_update}
            m = m_new
        tl.store(out_ptr + row, {finalize})
'''


def emit_kernel_source(sk: Skeleton, values: dict | None = None) -> str:
    """Render Triton source for one skeleton. The template branches on nothing."""
    check_supported(sk)
    return _TEMPLATE.format(
        name=sk.name,
        doc=sk.doc,
        prod_init=producer_init(sk),
        acc_init=consumer_init(sk),
        prod_update=producer_update(sk, values),
        acc_update=consumer_update(sk, values),
        abs_line="a = tl.abs(v)\n            " if producer_operand(sk, values) == "a" else "",
        init=sk.init,
        operand=producer_operand(sk, values),
        den_src=denominator_expr(sk),
        guard=guard_value(sk),
        scale_src=scale_source(sk, values),
        bias_line=bias_line(sk, values),
        term_src=term_source(sk, values),
        finalize=finalize_source(sk, values),
    )


def generated_path(name: str, values: dict | None = None) -> str:
    """One file per (skeleton, parameter values): the values are baked into the source."""
    tag = ""
    if values:
        tag = "_" + "_".join(f"{k}{float(v):g}" for k, v in sorted(values.items()))
    return os.path.join(_GEN_DIR, f"neptune_gen_{name}{tag}.py")


def compile_skeleton(name: str, values: dict | None = None, force: bool = False):
    """Generate -> write to a real file -> import -> return the kernel object."""
    cache_key = name + "|" + ",".join(f"{k}={float(v):g}" for k, v in sorted((values or {}).items()))
    if not force and cache_key in _CACHE:
        return _CACHE[cache_key]
    if name not in SKELETONS:
        raise KeyError(f"unknown skeleton {name!r}; have {all_registered()}")
    sk = SKELETONS[name]
    src = emit_kernel_source(sk, values)
    mod_name = f"neptune_gen_{name}_" + "".join(
        ch if ch.isalnum() else "_" for ch in cache_key.split("|", 1)[1])
    path = generated_path(name, values)
    with open(path, "w") as f:
        f.write(src)
    spec = importlib.util.spec_from_file_location(mod_name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[mod_name] = mod
    spec.loader.exec_module(mod)
    kernel = getattr(mod, name)
    _CACHE[cache_key] = kernel
    return kernel


def run(name: str, x, block: int = 1024, **params):
    """Execute the generated kernel, reducing over the last dimension.

    `params` supplies the extra scalars the skeleton declared, by kernel argument name
    (e.g. `run("lse_alibi", x, alpha=0.5)`).
    """
    import torch
    kernel = compile_skeleton(name, params)
    rows = x.shape[0]
    ncols = x.numel() // rows
    x2 = x.reshape(rows, ncols).contiguous()
    out = torch.empty(rows, device=x.device, dtype=torch.float32)
    kernel[(rows,)](x2, out, rows, ncols, x2.stride(0), BLOCK=block)
    return out
